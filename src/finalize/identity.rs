//! Remove machine identity that package postinstalls generate at build time.
//! The machine identity must instead be generated on first boot.

use anyhow::{Context, Result, ensure};
use cap_std_ext::cap_std::fs_utf8::Dir;
use cap_std_ext::dirext::{CapStdExtDirExt, CapStdExtDirExtUtf8};
use tracing::debug;

use super::GENERATED_HEADER;
use super::units;
use crate::distro::Distro;

/// The content of /etc/machine-id that marks the next boot as the first.
const MACHINE_ID_UNINITIALIZED: &[u8] = b"uninitialized\n";

/// The directory sshd and `ssh-keygen -A` keep the host keys in by default.
pub(super) const SSHD_HOST_KEY_DIR: &str = "/etc/ssh";

/// The unit generating the missing host keys.
pub(super) const SSHD_KEYGEN_UNIT: &str = "bootc-imagectl-sshd-keygen.service";

/// Delete machine identity files generated by package postinstalls at image build time.
pub(super) fn finalize(root: &Dir, distro: &dyn Distro) -> Result<()> {
    debug!("removing machine identity");

    // systemd treats `uninitialized` as a first boot. It generates the machine
    // ID and runs the units with `ConditionFirstBoot=yes`.
    root.write("etc/machine-id", MACHINE_ID_UNINITIALIZED)
        .context("resetting /etc/machine-id")?;

    // Host keys must be unique per machine. Not every distribution's sshd
    // generates missing ones, so we add a unit that does before sshd starts.
    if let Some(ssh) = root.open_dir_optional("etc/ssh")? {
        for entry in ssh.entries()? {
            let name = entry?.file_name()?;
            if name.starts_with("ssh_host_") {
                ssh.remove_file(&name)
                    .with_context(|| format!("removing /etc/ssh/{name}"))?;
            }
        }
    }
    if root.exists("etc/ssh/sshd_config") {
        write_sshd_keygen_unit(root)?;
    }

    let mounted = root.symlink_metadata_optional("etc/resolv.conf")?.is_some()
        && root
            .as_cap_std()
            .is_mountpoint("etc/resolv.conf")?
            .unwrap_or_default();
    ensure!(
        !mounted,
        "/etc/resolv.conf is mounted by the container runtime and cannot be removed. \
         help: run this step with RUN --network=none"
    );
    // The distribution's resolver creates it at boot.
    root.remove_file_optional("etc/resolv.conf")
        .context("removing /etc/resolv.conf")?;

    // The fstab packages create at install time is just a placeholder.
    root.remove_file_optional("etc/fstab")?;

    // Utilities like useradd and groupadd leave behind backup files that are not
    // needed in the image.
    for name in ["passwd", "group", "shadow", "gshadow", "subuid", "subgid"] {
        root.remove_file_optional(format!("etc/{name}-"))?;
    }
    root.remove_file_optional("etc/.pwd.lock")?;

    distro.remove_machine_identity(root)
}

/// Generate the missing host keys before sshd starts.
fn write_sshd_keygen_unit(root: &Dir) -> Result<()> {
    let unit = format!(
        "{GENERATED_HEADER}
[Unit]
Description=OpenSSH Server Key Generation
DefaultDependencies=no
After=local-fs.target
Before=sysinit.target shutdown.target
Conflicts=shutdown.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=ssh-keygen -A
"
    );
    units::write_enabled_unit(root, SSHD_KEYGEN_UNIT, &unit, "sysinit.target")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::finalize::units::VENDOR_UNIT_DIR;
    use crate::testutil::{TestDistro, rootfs};

    #[test]
    fn removes_build_time_identity() -> Result<()> {
        let root = rootfs()?;
        root.create_dir_all("etc/ssh")?;
        root.write("etc/machine-id", b"0123456789abcdef0123456789abcdef\n")?;
        root.write("etc/ssh/ssh_host_ed25519_key", b"secret")?;
        root.write("etc/ssh/ssh_host_ed25519_key.pub", b"public")?;
        root.write("etc/ssh/sshd_config", b"keep")?;
        root.write("etc/resolv.conf", b"")?;
        root.write("etc/fstab", b"")?;
        root.write("etc/passwd", b"root:x:0:0::/root:/bin/sh\n")?;
        root.write("etc/passwd-", b"backup")?;
        root.write("etc/.pwd.lock", b"")?;

        finalize(&root, &TestDistro::default())?;

        assert_eq!(root.read("etc/machine-id")?, MACHINE_ID_UNINITIALIZED);
        assert!(!root.exists("etc/ssh/ssh_host_ed25519_key"));
        assert!(!root.exists("etc/ssh/ssh_host_ed25519_key.pub"));
        assert!(root.exists("etc/ssh/sshd_config"));
        assert!(!root.exists("etc/resolv.conf"));
        assert!(!root.exists("etc/fstab"));
        assert!(root.exists("etc/passwd"));
        assert!(!root.exists("etc/passwd-"));
        assert!(!root.exists("etc/.pwd.lock"));
        Ok(())
    }

    #[test]
    fn enables_sshd_keygen_unit_with_sshd() -> Result<()> {
        let root = rootfs()?;
        root.create_dir_all("etc/ssh")?;
        root.write("etc/ssh/sshd_config", b"")?;
        finalize(&root, &TestDistro::default())?;
        assert_eq!(
            root.read_link_contents(format!(
                "{VENDOR_UNIT_DIR}/sysinit.target.wants/{SSHD_KEYGEN_UNIT}"
            ))?,
            format!("../{SSHD_KEYGEN_UNIT}")
        );
        Ok(())
    }

    #[test]
    fn skips_sshd_keygen_unit_without_sshd() -> Result<()> {
        let root = rootfs()?;
        root.create_dir("etc")?;
        finalize(&root, &TestDistro::default())?;
        assert!(!root.exists(format!("{VENDOR_UNIT_DIR}/{SSHD_KEYGEN_UNIT}")));
        Ok(())
    }

    #[test]
    fn removes_resolv_conf_symlink() -> Result<()> {
        let root = rootfs()?;
        root.create_dir("etc")?;
        root.symlink("../run/systemd/resolve/stub-resolv.conf", "etc/resolv.conf")?;
        finalize(&root, &TestDistro::default())?;
        assert!(root.symlink_metadata_optional("etc/resolv.conf")?.is_none());
        Ok(())
    }

    #[test]
    fn creates_missing_machine_id() -> Result<()> {
        let root = rootfs()?;
        root.create_dir("etc")?;
        finalize(&root, &TestDistro::default())?;
        assert_eq!(root.read("etc/machine-id")?, MACHINE_ID_UNINITIALIZED);
        Ok(())
    }
}
